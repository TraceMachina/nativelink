#!/usr/bin/env python3
"""Prepare a NativeLink release: bump versions, lockfiles, and CHANGELOG.md.

Works both locally (in a maintainer's fork or worktree) and inside GitHub
Actions (on upstream or a fork). Re-running with the same version after
adjusting `cliff.toml` replaces the top `CHANGELOG.md` section in place.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import re
import subprocess
import sys

UPSTREAM_GIT_URL = "https://github.com/TraceMachina/nativelink.git"
SEMVER_RE = re.compile(r"^v?(\d+\.\d+\.\d+)$")


def run(cmd: list[str], cwd: pathlib.Path, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=cwd, text=True, capture_output=True, check=check)


def repo_root() -> pathlib.Path:
    out = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
    return pathlib.Path(out)


def fetch_upstream_tags(root: pathlib.Path) -> None:
    remotes = run(["git", "remote"], cwd=root).stdout.splitlines()
    target = "upstream" if "upstream" in remotes else UPSTREAM_GIT_URL
    res = run(["git", "fetch", "--tags", "--quiet", target], cwd=root, check=False)
    if res.returncode != 0:
        print(
            f"warning: could not fetch tags from {target}: {res.stderr.strip()}",
            file=sys.stderr,
        )


def update_module_bazel(path: pathlib.Path, version: str) -> None:
    text = path.read_text(encoding="utf-8")
    updated, count = re.subn(
        r'(module\(\s*name\s*=\s*"nativelink",\s*version\s*=\s*")(\d+\.\d+\.\d+)(")',
        rf"\g<1>{version}\g<3>",
        text,
        count=1,
    )
    if count != 1:
        raise RuntimeError(f"Expected 1 module version in {path}, matched {count}")
    path.write_text(updated, encoding="utf-8")


def update_cargo_toml(path: pathlib.Path, version: str) -> None:
    text = path.read_text(encoding="utf-8")
    # Update version = "..." inside [workspace.package] and [package] tables.
    updated, count = re.subn(
        r'(^version\s*=\s*")(\d+\.\d+\.\d+)(")',
        rf"\g<1>{version}\g<3>",
        text,
        flags=re.MULTILINE,
    )
    if count < 1:
        raise RuntimeError(f"Expected version field in {path}, matched {count}")
    path.write_text(updated, encoding="utf-8")


def update_cargo_lock(path: pathlib.Path, version: str) -> None:
    text = path.read_text(encoding="utf-8")

    def replace_pkg(match: re.Match[str]) -> str:
        name = match.group("name")
        if name == "nativelink-fuzz":
            return match.group(0)
        return f'{match.group("prefix")}{version}{match.group("suffix")}'

    pattern = re.compile(
        r'(?P<prefix>\[\[package\]\]\nname = "(?P<name>nativelink(?:-[a-z0-9-]+)?)"\nversion = ")'
        r"\d+\.\d+\.\d+"
        r'(?P<suffix>"\n(?!source = ))'
    )
    updated, count = pattern.subn(replace_pkg, text)
    if count < 1:
        raise RuntimeError(f"Expected nativelink packages in {path}, matched {count}")
    path.write_text(updated, encoding="utf-8")


def strip_existing_version_section(changelog_path: pathlib.Path, version: str) -> None:
    """If CHANGELOG.md already starts with `## [version]`, remove that section so
    re-running after editing `cliff.toml` regenerates it cleanly."""
    text = changelog_path.read_text(encoding="utf-8")
    pattern = re.compile(
        rf"^## \[{re.escape(version)}\].*?\n(?=^## \[|\Z)",
        flags=re.MULTILINE | re.DOTALL,
    )
    updated, count = pattern.subn("", text, count=1)
    if count:
        changelog_path.write_text(updated, encoding="utf-8")


def extract_version_section(changelog_path: pathlib.Path, version: str) -> str:
    text = changelog_path.read_text(encoding="utf-8")
    match = re.search(
        rf"(^## \[{re.escape(version)}\].*?)(?=^## \[|^<!-- generated by git-cliff -->|\Z)",
        text,
        flags=re.MULTILINE | re.DOTALL,
    )
    return match.group(1).strip() if match else ""


def extract_misc_commits(section: str) -> list[str]:
    match = re.search(
        r"^### .*Miscellaneous\s*\n(.*?)(?=^### |\Z)",
        section,
        flags=re.MULTILINE | re.DOTALL,
    )
    if not match:
        return []
    return [
        line.strip()
        for line in match.group(1).splitlines()
        if line.strip().startswith("- ")
    ]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Bump NativeLink version, lockfiles, and prepend CHANGELOG.md."
    )
    parser.add_argument(
        "version",
        help="Target release version (e.g. v1.8.1 or 1.8.1).",
    )
    parser.add_argument(
        "--no-fetch-tags",
        action="store_true",
        help="Skip fetching tags from upstream before running git-cliff.",
    )
    parser.add_argument(
        "--write-section",
        type=pathlib.Path,
        default=None,
        help="Optional file path to write the generated CHANGELOG.md section to.",
    )
    args = parser.parse_args()

    m = SEMVER_RE.match(args.version.strip())
    if not m:
        print(
            f"error: '{args.version}' is not a valid release version (expected vMAJOR.MINOR.PATCH or MAJOR.MINOR.PATCH)",
            file=sys.stderr,
        )
        return 1

    version = m.group(1)
    tag = f"v{version}"
    root = repo_root()

    if not args.no_fetch_tags:
        fetch_upstream_tags(root)

    update_module_bazel(root / "MODULE.bazel", version)
    update_cargo_toml(root / "Cargo.toml", version)
    update_cargo_lock(root / "Cargo.lock", version)
    update_cargo_lock(root / "nativelink-test/fuzz/Cargo.lock", version)

    taplo_bin = os.environ.get("TAPLO_BIN", "taplo")
    run([taplo_bin, "fmt", "Cargo.toml"], cwd=root, check=False)

    changelog_path = root / "CHANGELOG.md"
    strip_existing_version_section(changelog_path, version)

    git_cliff_bin = os.environ.get("GIT_CLIFF_BIN", "git-cliff")
    run(
        [
            git_cliff_bin,
            "--unreleased",
            f"--tag={tag}",
            "--prepend",
            "CHANGELOG.md",
        ],
        cwd=root,
    )

    section = extract_version_section(changelog_path, version)
    if args.write_section is not None:
        args.write_section.write_text(section + "\n", encoding="utf-8")

    misc = extract_misc_commits(section)
    print(f"Prepared NativeLink {tag}:")
    print("  - MODULE.bazel")
    print("  - Cargo.toml")
    print("  - Cargo.lock")
    print("  - nativelink-test/fuzz/Cargo.lock")
    print("  - CHANGELOG.md")
    if misc:
        print(
            "\nCommits grouped under '⚙️ Miscellaneous' (add rules to cliff.toml and re-run if needed):"
        )
        for item in misc:
            print(f"  {item}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
