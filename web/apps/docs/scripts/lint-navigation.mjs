#!/usr/bin/env node
// Navigation lint: no page on the reading path is a dead end, and no page off
// it claims to be on it.
//
// The docs are ordered as a path (cache, then execution, then configuration,
// then how-to guides) and that ordering only exists if every page on it says
// what comes next. A page without a `<NextStep>` is where the path stops for
// the reader who reached it, regardless of how well the sidebar is organised.
//
// A page may offer more than one `<NextStep>`, but only one of them is the
// path. The rest are marked `kind="aside"` and render as optional detours, so
// the reader is never asked to pick blind between two equal-looking doors. So
// what this counts is *primary* next steps: exactly one per page.
//
// The inverse matters as much. A `<Prerequisites>` block tells the reader what
// the page assumes they already have, which only makes sense on a page that
// sits somewhere in the sequence. Reference, concept and contribute pages are
// entered from a search or a link rather than from the page before, and they
// carry none.
//
// So this checks three things:
//
//   1. Every non-index page on the path has a primary `<NextStep>`.
//   2. No page has two primary `<NextStep>`s.
//   3. No page outside the path sections has a `<Prerequisites>`.
//
// Section index pages are exempt from the first rule: they are the fan-out
// for their section, and the list of links IS the "what next".
//
// Fenced code blocks are stripped before anything is counted, so the page that
// documents these components for contributors does not trip the lint by
// showing what they look like.
//
// Usage, from web/:
//   bun --filter @nativelink/docs lint:navigation
// or directly:
//   node scripts/lint-navigation.mjs
//
// Exit code is 1 if any page is a dead end or states prerequisites it should not.

import { readFileSync, readdirSync, statSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = join(here, "..");
const contentDir = join(docsRoot, "content/docs");

// The provenance comment generated pages open with. Matching the comment form
// rather than the bare word keeps a page that merely mentions the marker in
// prose from being treated as generated.
const GENERATED_MARKER = "{/* AUTOGENERATED";

// The sections that form the reading path, in order, plus the two that sit
// either side of it. Every page in these wants a `<NextStep>` and may open with
// `<Prerequisites>`.
const PATH_SECTIONS = [
  "use-cases",
  "getting-started",
  "remote-execution",
  "configuration",
  "how-to",
  "operate",
];

// --------------------------------------------------------------------------

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith(".mdx")) out.push(full);
  }
  return out;
}

function sectionOf(file) {
  const rel = relative(contentDir, file).replace(/\\/g, "/");
  const slash = rel.indexOf("/");
  return slash === -1 ? "" : rel.slice(0, slash);
}

// Fenced blocks and inline code are prose about the components, not uses of
// them. contribute/docs.mdx shows a `<Prerequisites>` in a fence to explain
// the convention, and it should not be held to it.
function stripCode(source) {
  return source.replace(/^```[\s\S]*?^```/gm, "\n").replace(/`[^`\n]*`/g, "``");
}

// `<NextStep … kind="aside">` is an optional detour. Everything else is the
// path. Attributes may wrap across lines, so match up to the closing `>` of
// the opening tag rather than to end of line.
function countNextSteps(source) {
  const opens = source.match(/<NextStep\b[^>]*>/g) ?? [];
  let primary = 0;
  let asides = 0;
  for (const tag of opens) {
    if (/\bkind\s*=\s*["'{]?\s*aside/.test(tag)) asides += 1;
    else primary += 1;
  }
  return { primary, asides };
}

function main() {
  const files = walk(contentDir).sort();
  const problems = [];
  const seenSections = new Set();
  let checked = 0;

  for (const file of files) {
    const rel = relative(docsRoot, file).replace(/\\/g, "/");
    const raw = readFileSync(file, "utf8");
    if (raw.includes(GENERATED_MARKER)) continue;
    const source = stripCode(raw);

    const section = sectionOf(file);
    if (section) seenSections.add(section);

    const onPath = PATH_SECTIONS.includes(section);
    const isIndex = basename(file) === "index.mdx";

    const { primary } = countNextSteps(source);
    const prerequisites = source.match(/<Prerequisites\b/g)?.length ?? 0;

    checked += 1;

    if (onPath && !isIndex && primary === 0) {
      problems.push({
        rel,
        message:
          "no primary <NextStep>: this page is on the reading path, so it is " +
          "where the path stops for whoever lands here " +
          '(a page with only `kind="aside"` steps offers detours and no road)',
      });
    }

    if (primary > 1) {
      const detail =
        "one of these is the path and the rest want " + '`kind="aside"`, or the reader picks blind';
      problems.push({
        rel,
        message: `${primary} primary <NextStep> elements: ${detail}`,
      });
    }

    if (!onPath && prerequisites > 0) {
      problems.push({
        rel,
        message: `<Prerequisites> on a page in \`${section || "the docs root"}\`, which is not on the reading path: it would tell the reader they are partway through a sequence they are not in`,
      });
    }
  }

  // A renamed or removed section would otherwise make this lint quietly stop
  // checking the pages it was written for.
  for (const section of PATH_SECTIONS) {
    if (!seenSections.has(section)) {
      problems.push({
        rel: "scripts/lint-navigation.mjs",
        message: `PATH_SECTIONS names \`${section}\`, which has no pages`,
      });
    }
  }

  if (problems.length === 0) {
    console.log(`lint:navigation: ${checked} pages, no dead ends, no misplaced prerequisites.`);
    return;
  }

  console.error(`lint:navigation: ${problems.length} problem(s):\n`);
  for (const { rel, message } of problems) {
    console.error(`  ${rel}  ${message}`);
  }
  console.error(
    "\nPages on the reading path end with exactly one primary <NextStep> so the\n" +
      'path continues; further links go as `kind="aside"`. Pages off the path\n' +
      "carry no <Prerequisites>, because they are entered from a search or a\n" +
      "link rather than from the page before.\n",
  );
  process.exit(1);
}

main();
