#!/usr/bin/env node
// Link lint: every internal link resolves to a page that exists, at an anchor
// that exists.
//
// A 404 is loud. The failures this lint exists for are the quiet ones: a link
// to a page that still exists but whose section was renamed, so the browser
// silently lands at the top and the reader never learns they were sent
// somewhere specific. Humans notice they are in the wrong place and scroll.
// Agents do not; they follow the URL, take the top of the page, and quote it
// as the answer to a question it does not answer.
//
// So this checks three things, in increasing order of how easy they are to
// break without noticing:
//
//   1. `/some/page` resolves to a real .mdx file (or to a configured redirect).
//   2. `/some/page#some-anchor` resolves to an anchor that page actually
//      declares.
//   3. `#local-anchor` inside a page resolves on that same page.
//
// It deliberately does NOT check external links. Those fail for reasons
// outside this repository (rate limits, transient outages, sites that block
// CI), and a lint that goes red for reasons a contributor cannot fix is a
// lint people learn to ignore. External reachability belongs in a scheduled
// job, not in the PR gate.
//
// Links to a served file rather than to a page (`/llms.txt`, an image, a
// downloadable config) are skipped. Whether those exist is decided by the
// build and by `public/`, not by anything in content/docs, so this lint has no
// way to answer the question and no business guessing.
//
// Generated pages get checked but not enforced, for the same reason: a broken
// link on a generated page is a bug in the generator, and failing an unrelated
// PR for it teaches contributors that this lint is somebody else's problem.
// They are reported separately, as warnings, so the bug is visible to whoever
// owns the generator.
//
// Usage, from web/:
//   bun --filter @nativelink/docs lint:links
// or directly:
//   node scripts/lint-links.mjs
//
// Exit code is 1 if any internal link is unresolvable.

import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { remarkHeading } from "fumadocs-core/mdx-plugins";
import remarkMdx from "remark-mdx";
import remarkParse from "remark-parse";
import { unified } from "unified";
import { visit } from "unist-util-visit";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = join(here, "..");
const contentDir = join(docsRoot, "content/docs");

// Routes that exist but are not backed by an .mdx file in content/docs.
const EXTRA_ROUTES = new Set(["/"]);

// A final path segment with an extension is a served file, not a page; see
// the header. The extension must start with a letter so a version segment like
// `/reference/v0.62` is still treated as a route.
const SERVED_FILE = /\/[^/]+\.[a-z][a-z0-9]{1,4}$/i;

// Same marker lint-anchors uses to recognise a page it must not rewrite.
// The provenance comment generated pages open with. Matching the comment form
// rather than the bare word keeps a page that merely mentions the marker in
// prose from being treated as generated.
const GENERATED_MARKER = "{/* AUTOGENERATED";

// --------------------------------------------------------------------------

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith(".mdx") || name.endsWith(".md")) out.push(full);
  }
  return out;
}

/**
 * content/docs/a/b.mdx -> /a/b ; content/docs/a/index.mdx -> /a
 *
 * `.md` counts too. Fumadocs serves both, and `reference/changelog.md` is a
 * real page; indexing only `.mdx` reported every link to it as a dead link.
 */
function routeFor(file) {
  const rel = relative(contentDir, file).replace(/\\/g, "/");
  const noExt = rel.replace(/\.mdx?$/, "");
  const route = noExt.endsWith("/index")
    ? noExt.slice(0, -"/index".length)
    : noExt === "index"
      ? ""
      : noExt;
  return `/${route}`.replace(/\/$/, "") || "/";
}

function blankFrontmatter(source) {
  if (!source.startsWith("---")) return source;
  const end = source.indexOf("\n---", 3);
  if (end === -1) return source;
  const close = source.indexOf("\n", end + 1);
  const head = source.slice(0, close);
  return head.replace(/[^\n]/g, " ") + source.slice(close);
}

const processor = unified()
  .use(remarkParse)
  .use(remarkMdx)
  .use(remarkHeading, { generateToc: false });

// Plain `.md` pages are Markdown, not MDX. `reference/changelog.md` is
// assembled from upstream release notes and contains `<!-- -->` comments and
// bare `<` characters that are a syntax error under remarkMdx. They are still
// real pages that real links point at, so they get parsed, just not as MDX.
const mdProcessor = unified().use(remarkParse).use(remarkHeading, { generateToc: false });

/**
 * Anchors a page offers, and internal links a page makes.
 *
 * Heading ids come from Fumadocs' own `remarkHeading`, so what this collects
 * is what the site actually serves, including on generated pages, where the
 * anchors are the generator's and there is no explicit `[#slug]` to read.
 */
function inspect(source, { mdx = true } = {}) {
  const p = mdx ? processor : mdProcessor;
  const tree = p.parse(blankFrontmatter(source));
  p.runSync(tree);

  const anchors = new Set();
  const links = [];

  visit(tree, "heading", (node) => {
    const id = node.data?.hProperties?.id;
    if (id) anchors.add(id);
  });

  visit(tree, "link", (node) => {
    links.push({ href: node.url, line: node.position.start.line });
  });

  visit(tree, "mdxJsxFlowElement", collectJsx);
  visit(tree, "mdxJsxTextElement", collectJsx);

  function collectJsx(node) {
    for (const attr of node.attributes ?? []) {
      if (attr.type !== "mdxJsxAttribute") continue;
      if (attr.name === "id" && node.name === "Accordion") {
        if (typeof attr.value === "string") anchors.add(attr.value);
      }
      if (attr.name !== "href") continue;
      if (typeof attr.value !== "string") continue;
      links.push({ href: attr.value, line: node.position.start.line });
    }
  }

  return { anchors, links };
}

/**
 * The `redirects()` table out of next.config.mjs, without importing it.
 *
 * Importing the config would be the obvious thing, and it is the wrong thing:
 * the first line of that file is `createMDX()`, so an import drags in
 * fumadocs-mdx, which compiles the MDX config through esbuild's
 * platform-specific native binary and writes to `.source/`. A link lint that
 * cannot run unless the whole MDX toolchain is installed and matches the host
 * architecture is a link lint that gets skipped.
 *
 * The `redirects()` body is pure data (array literals, `Object.entries`,
 * spreads) and closes over nothing in module scope, so it can be lifted out
 * by brace matching and evaluated on its own. If that extraction ever stops
 * working, every redirected route reports as an unresolved link, which is a
 * loud failure pointing straight here rather than a quiet one.
 */
function redirectTable(configSource) {
  const start = configSource.indexOf("async redirects()");
  if (start === -1) throw new Error("no `async redirects()` in next.config.mjs");
  const open = configSource.indexOf("{", start);
  let depth = 0;
  let end = -1;
  for (let i = open; i < configSource.length; i += 1) {
    if (configSource[i] === "{") depth += 1;
    else if (configSource[i] === "}" && --depth === 0) {
      end = i;
      break;
    }
  }
  if (end === -1) throw new Error("unbalanced braces in redirects()");
  // Repo-local file, and the body is data: no imports, no closures.
  const list = new Function(`"use strict";${configSource.slice(open + 1, end)}`)();
  if (!Array.isArray(list) || list.length === 0) {
    throw new Error("redirects() did not evaluate to a non-empty array");
  }
  return list;
}

/**
 * Redirect sources from next.config.mjs, so a link to a page that moved is
 * correct rather than merely tolerated.
 *
 * Patterns with a `:param` segment become a prefix match: `/old/:slug*`
 * accepts anything under `/old/`. If the config cannot be read we carry on
 * with an empty table rather than failing: a missing redirect surfaces as an
 * unresolved link, which is the more useful error.
 */
async function loadRedirects() {
  const exact = new Set();
  const prefixes = [];
  try {
    const list = redirectTable(readFileSync(join(docsRoot, "next.config.mjs"), "utf8"));
    for (const { source } of list) {
      if (typeof source !== "string") continue;
      const param = source.indexOf("/:");
      if (param === -1) exact.add(source.replace(/\/$/, "") || "/");
      else prefixes.push(source.slice(0, param));
    }
  } catch (error) {
    console.warn(`  note: could not read next.config.mjs redirects (${error.message})`);
    console.warn("  every link to a page that moved will report as unresolved.");
  }
  return { exact, prefixes };
}

// --------------------------------------------------------------------------

async function main() {
  const files = walk(contentDir).sort();
  const pages = new Map();

  for (const file of files) {
    const source = readFileSync(file, "utf8");
    let report;
    try {
      report = inspect(source, { mdx: file.endsWith(".mdx") });
    } catch (error) {
      console.error(`${relative(docsRoot, file)}:1  could not parse: ${error.message}`);
      process.exit(1);
    }
    pages.set(routeFor(file), {
      file,
      generated: source.includes(GENERATED_MARKER),
      ...report,
    });
  }

  const redirects = await loadRedirects();
  const problems = [];
  const warnings = [];
  let checked = 0;

  const isRedirected = (route) =>
    redirects.exact.has(route) ||
    redirects.prefixes.some((p) => route === p.replace(/\/$/, "") || route.startsWith(p));

  for (const [, page] of pages) {
    const rel = relative(docsRoot, page.file);
    // Generated pages are reported but do not fail the run; see the header.
    const report = page.generated ? warnings : problems;

    for (const { href, line } of page.links) {
      // External, mail, and protocol-relative links are not this lint's job.
      if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith("//")) continue;
      // A served file, not a page; see the header.
      if (SERVED_FILE.test(href.split("#")[0])) continue;

      checked += 1;
      const hash = href.indexOf("#");
      const path = hash === -1 ? href : href.slice(0, hash);
      const anchor = hash === -1 ? "" : href.slice(hash + 1);

      // A bare `#anchor` is a link within this page.
      if (path === "") {
        if (anchor && !page.anchors.has(anchor)) {
          report.push({ rel, line, message: `no anchor \`#${anchor}\` on this page` });
        }
        continue;
      }

      if (!path.startsWith("/")) {
        report.push({
          rel,
          line,
          message: `relative link \`${href}\`: internal links must be absolute from the docs\n        root. If you meant a reference-style link, the brackets are \`[text][${href}]\`, not \`[text](${href})\`.`,
        });
        continue;
      }

      const target = path.replace(/\/$/, "") || "/";
      const targetPage = pages.get(target);

      if (!targetPage) {
        if (EXTRA_ROUTES.has(target) || isRedirected(target)) continue;
        // The most common shape of this failure is worth naming outright.
        const near = [...pages.keys()].find((r) => r.endsWith(target) || target.endsWith(r));
        report.push({
          rel,
          line,
          message: near
            ? `\`${target}\` does not exist. Did you mean \`${near}\`?`
            : `\`${target}\` does not exist, and no redirect covers it`,
        });
        continue;
      }

      if (anchor && !targetPage.anchors.has(anchor)) {
        report.push({
          rel,
          line,
          message: `\`${target}\` exists but declares no anchor \`#${anchor}\``,
        });
      }
    }
  }

  if (warnings.length > 0) {
    console.warn(`lint:links: ${warnings.length} unresolved link(s) on generated pages.`);
    console.warn(
      "These do not fail the build: the fix belongs in the generator, not in\n" +
        "the page, and not in whichever PR happened to run this next.\n",
    );
    for (const { rel, line, message } of warnings) {
      console.warn(`  ${rel}:${line}  ${message}`);
    }
    console.warn("");
  }

  if (problems.length === 0) {
    console.log(`lint:links: ${checked} internal links across ${pages.size} pages resolve.`);
    return;
  }

  console.error(`lint:links: ${problems.length} unresolved of ${checked} internal links:\n`);
  for (const { rel, line, message } of problems) {
    console.error(`  ${rel}:${line}  ${message}`);
  }
  console.error(
    "\nEvery internal link must resolve to a page that exists, at an anchor that\n" +
      "exists. If a page moved, add a redirect in next.config.mjs; the redirect\n" +
      "table counts as resolution, so old published URLs stay valid.\n",
  );
  process.exit(1);
}

await main();
