#!/usr/bin/env node
// Generate `public/llms.txt`, `public/llms-small.txt` and `public/llms-full.txt`
// from the navigation.
//
// Three files, one job: give a machine reader the same corpus a human gets
// from the sidebar, in the same order, without asking it to crawl.
//
//   /llms.txt        the link index: every published page, one line each, in
//                    reading order, following https://llmstxt.org/
//   /llms-small.txt  the abridged corpus: every page's headings and the prose
//                    that opens each section, without code samples, tables or
//                    components, for an agent that would rather spend its
//                    context on the question than on the docs
//   /llms-full.txt   the same order with page bodies inlined, so an agent can
//                    fetch once instead of following 70 links
//
// All three are generated from `meta.json` and page frontmatter. That is the
// whole point: a hand-maintained index is a second source of truth, and a
// second source of truth is a page that is wrong six weeks from now. Add a
// page to a `meta.json` and it appears here; delete one and it disappears;
// reword a description in frontmatter and this file says the same thing the
// page does.
//
// Usage, from web/:
//   bun --filter @nativelink/docs gen:llms
// or directly:
//   node scripts/gen-llms.mjs
//
// Runs as part of `dev` and `build`, after `gen:changelog`, because the
// changelog page is itself generated.
//
// The marketing site's generator (web/apps/web/scripts/gen-llms.ts) imports
// the builders below to fold this corpus into nativelink.com's own llms files,
// which is why they are exported and why `main()` only runs when this file is
// the entry point.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = join(here, "..");
const contentDir = join(docsRoot, "content/docs");
const publicDir = join(docsRoot, "public");

const SITE = "https://docs.nativelink.com";
const REPO = "https://github.com/TraceMachina/nativelink";

/** Pages a machine reader should know about that are not part of the docs nav. */
const APPENDIX = [
  {
    section: "For agents",
    title: "AGENTS.md",
    url: `${REPO}/blob/main/AGENTS.md`,
    description:
      "the repository map for an agent working on the code: what each crate owns, " +
      "where to change what, and which doc has to follow each kind of change.",
  },
  {
    section: "Optional",
    title: "NativeLink on GitHub",
    url: REPO,
    description: "source, issues, releases.",
  },
  {
    section: "Optional",
    title: "Remote Execution API",
    url: "https://github.com/bazelbuild/remote-apis",
    description: "the protocol NativeLink implements.",
  },
];

const PREAMBLE = `> A remote build cache and remote execution service in one Rust binary, for
> build systems that speak the Remote Execution API: Bazel, Buck2, Siso,
> Pants, BuildStream, and CMake via recc. The cache, the scheduler and the
> worker are the same executable started with different configuration.

These docs are ordered as a path, not a catalogue: get a cache serving hits,
then put workers behind the misses, then own the config file, then reach for
the how-to guides. Each section assumes the previous one is working, and every
page on the path opens by stating what it assumes. An agent reading this file
in order learns the same sequence a human learns from the sidebar.

Getting started, then Remote execution, then Configuration, then How-to guides.
Why NativeLink comes before that path, and Operate comes after it. Concepts,
Reference and Contribute are outside the ordering: enter them from a search or
a link at any point.`;

const GENERATED_NOTE = `This file is generated from the navigation (\`meta.json\`) and page frontmatter
by \`web/apps/docs/scripts/gen-llms.mjs\`, so it cannot drift from the sidebar.`;

// The provenance comment generated pages open with. Matching the comment form
// rather than the bare word keeps a page that merely mentions the marker in
// prose from being treated as generated.
const GENERATED_MARKER = "{/* AUTOGENERATED";

// --------------------------------------------------------------------------

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

/** Frontmatter is small and well-formed here; a full YAML parser is overkill. */
function parseFrontmatter(source, path) {
  if (!source.startsWith("---\n")) {
    throw new Error(`${path} has no frontmatter`);
  }
  const end = source.indexOf("\n---", 3);
  if (end === -1) throw new Error(`${path} has an unterminated frontmatter block`);
  const bodyStart = source.indexOf("\n", end + 1) + 1;
  const data = {};
  let key = null;
  for (const line of source.slice(4, end).split("\n")) {
    const match = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (match) {
      key = match[1];
      data[key] = match[2].trim();
    } else if (key && line.trim()) {
      // A folded continuation line, which frontmatter descriptions use freely.
      data[key] = `${data[key]} ${line.trim()}`.trim();
    }
  }
  for (const k of Object.keys(data)) {
    data[k] = data[k].replace(/^["'](.*)["']$/, "$1");
  }
  return { data, body: source.slice(bodyStart) };
}

/** Locate the file backing a nav entry, whichever extension it uses. */
function pageFile(dir, name) {
  for (const ext of [".mdx", ".md"]) {
    const candidate = join(dir, name + ext);
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

function isDirectory(dir, name) {
  return existsSync(join(dir, name)) && existsSync(join(dir, name, "meta.json"));
}

/**
 * Walk a directory's `meta.json` in order and return its pages.
 *
 * Nav order is the reading order, so this walk *is* the journey: whatever comes
 * out of it is what both generated files say, in the order the sidebar says it.
 */
function collectPages(dir, urlPrefix, out) {
  const meta = readJson(join(dir, "meta.json"));
  const pages = meta.pages ?? [];
  // A folder's index page is the folder's own link in the sidebar, so
  // meta.json does not list it; it still comes first in reading order.
  if (!pages.includes("index") && pageFile(dir, "index")) pages.unshift("index");
  for (const entry of pages) {
    if (entry.startsWith("---")) continue; // a sidebar separator, handled by the caller
    if (isDirectory(dir, entry)) {
      collectPages(join(dir, entry), `${urlPrefix}/${entry}`, out);
      continue;
    }
    const file = pageFile(dir, entry);
    if (!file) {
      throw new Error(
        `${join(dir, "meta.json")} lists "${entry}", but no such page exists. ` +
          "Either the nav entry is stale or the page was never created.",
      );
    }
    const source = readFileSync(file, "utf8");
    const { data, body } = parseFrontmatter(source, file);
    out.push({
      url: entry === "index" ? urlPrefix || "/" : `${urlPrefix}/${entry}`,
      title: data.title ?? entry,
      description: data.description ?? "",
      body,
      generated: source.includes(GENERATED_MARKER) || body.includes("Generated by scripts/"),
    });
  }
  return out;
}

/**
 * The whole corpus, as a flat list of sections in nav order.
 */
function buildSections() {
  const rootMeta = readJson(join(contentDir, "meta.json"));
  const sections = [];

  for (const entry of rootMeta.pages ?? []) {
    if (entry.startsWith("---")) continue; // a sidebar separator carries no pages
    if (isDirectory(contentDir, entry)) {
      // The section's own sidebar title names it, so llms.txt and the sidebar
      // cannot disagree.
      const title = readJson(join(contentDir, entry, "meta.json")).title ?? entry;
      sections.push({
        title,
        pages: collectPages(join(contentDir, entry), `/${entry}`, []),
      });
      continue;
    }
    const file = pageFile(contentDir, entry);
    if (!file) throw new Error(`content/docs/meta.json lists "${entry}", but no such page exists`);
    const { data, body } = parseFrontmatter(readFileSync(file, "utf8"), file);
    sections.push({
      title: null, // the root page is the front door, not a section
      pages: [
        {
          url: "/",
          title: data.title ?? entry,
          description: data.description ?? "",
          body,
          generated: false,
        },
      ],
    });
  }

  for (const extra of APPENDIX) {
    const section = sections.find((s) => s.title === extra.section);
    if (section) section.pages.push({ ...extra, external: true });
    else sections.push({ title: extra.section, pages: [{ ...extra, external: true }] });
  }

  return sections;
}

// --------------------------------------------------------------------------

function renderIndex(sections) {
  const lines = [
    "# NativeLink",
    "",
    PREAMBLE,
    "",
    GENERATED_NOTE,
    "",
    "The full corpus with page bodies is at /llms-full.txt; an abridged copy,",
    "prose only, is at /llms-small.txt.",
    "",
  ];

  for (const section of sections) {
    if (section.title) lines.push(`## ${section.title}`, "");
    for (const page of section.pages) {
      const url = page.external ? page.url : `${SITE}${page.url}`;
      lines.push(`- [${page.title}](${url}): ${page.description}`);
    }
    lines.push("");
  }

  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

/**
 * Strip the machinery a reader does not need: the archetype pointer, the lint
 * escape hatches. Everything else, components included, is left verbatim,
 * because a lossy transcription of a page is a third source of truth.
 */
function cleanBody(body) {
  return body
    .replace(/^\{\/\*\s*archetype:[^]*?\*\/\}\s*$/gm, "")
    .replace(/^\{\/\*\s*lint-snippets:[^]*?\*\/\}\s*$/gm, "")
    .replace(/^\{\/\*\s*AUTOGENERATED[^]*?\*\/\}\s*$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Cut a block at a sentence boundary once it passes `max` characters, so an
 * abridged section reads as prose that stops rather than prose that breaks.
 */
function truncateBlock(block, max) {
  if (block.length <= max) return block;
  const head = block.slice(0, max);
  const end = Math.max(head.lastIndexOf(". "), head.lastIndexOf(".\n"));
  return end > max / 2 ? head.slice(0, end + 1) : `${head.trimEnd()}…`;
}

/**
 * Abridge one page body for `llms-small.txt`.
 *
 * Keeps every heading (without its explicit anchor) and the first prose block
 * under each, cut at a sentence boundary, so the skeleton of the page and the
 * sentence that opens each section survive. Drops fenced code, tables, MDX
 * component tags (their inner text stays), the navigation blocks
 * (`<Prerequisites>`, `<NextStep>`) and JSX expressions. The result says what
 * each page and section is about, in the page's own words, at about a fifth
 * of the size; a reader who needs the code or the tables fetches the page, or
 * the full corpus.
 */
function abridgeBody(body, blocksPerSection = 1, blockChars = 420) {
  const text = cleanBody(body)
    .replace(/^[ \t]*```[^\n]*\n[\s\S]*?^[ \t]*```[ \t]*$/gm, "")
    .replace(/<NextStep\b[\s\S]*?<\/NextStep>/g, "")
    .replace(/<Prerequisites\b[\s\S]*?<\/Prerequisites>/g, "")
    .replace(/<\/?[A-Z][\w.]*\b(?:"[^"]*"|'[^']*'|\{[^}]*\}|[^>])*\/?>/g, "")
    .replace(/^(#{1,6} .*?)\s*\[#[^\]]+\][ \t]*$/gm, "$1");

  const out = [];
  let kept = 0;
  for (const raw of text.split(/\n[ \t]*\n/)) {
    const block = raw.trim();
    if (!block) continue;
    if (/^#{1,6} /.test(block)) {
      out.push(block);
      kept = 0;
      continue;
    }
    if (kept >= blocksPerSection) continue;
    if (block.startsWith("|") || block.startsWith("{") || block.startsWith("<!--")) continue;
    out.push(truncateBlock(block, blockChars));
    kept += 1;
  }
  return out.join("\n\n");
}

function renderSmall(sections) {
  const lines = [
    "# NativeLink: abridged documentation corpus",
    "",
    PREAMBLE,
    "",
    GENERATED_NOTE,
    "",
    `Every page below is delimited by a heading of the form \`# ${SITE}/<path>\`,`,
    "giving that page's canonical URL. This is the abridged corpus: each page",
    "keeps its headings and the prose that opens each section, and drops code",
    "samples, tables, components and navigation. It is meant to fit in a context",
    "window alongside the question being asked. When a section here is the one",
    "you need, fetch its page, or the whole corpus at /llms-full.txt.",
    "",
  ];

  for (const section of sections) {
    for (const page of section.pages) {
      if (page.external) continue;
      lines.push("", `# ${SITE}${page.url}`, "");
      lines.push(`**${page.title}**: ${page.description}`);
      lines.push("");
      if (page.generated) {
        lines.push(`_Generated reference page, not inlined. Fetch it from ${SITE}${page.url}._`);
      } else {
        lines.push(abridgeBody(page.body));
      }
    }
  }

  return `${lines
    .join("\n")
    .replace(/\n{4,}/g, "\n\n\n")
    .trimEnd()}\n`;
}

function renderFull(sections) {
  const lines = [
    "# NativeLink: full documentation corpus",
    "",
    PREAMBLE,
    "",
    GENERATED_NOTE,
    "",
    `Every page below is delimited by a heading of the form \`# ${SITE}/<path>\`,`,
    "giving that page's canonical URL. The delimiter is the absolute URL rather",
    "than the path because a bare `# /path` line is indistinguishable from a shell",
    "comment naming a file, and several pages contain exactly that.",
    "",
    "Page bodies are reproduced verbatim, MDX components included, so nothing is",
    "lost in transcription; links inside them are site-relative and resolve against",
    `${SITE}. The generated reference pages (the configuration`,
    "reference, the metrics reference and the changelog) are linked rather than",
    "inlined: they are long, they change on a different cadence from the prose, and",
    "they are better fetched on demand.",
    "",
  ];

  for (const section of sections) {
    for (const page of section.pages) {
      if (page.external) continue;
      lines.push("", `# ${SITE}${page.url}`, "");
      lines.push(`**${page.title}**: ${page.description}`);
      lines.push("");
      if (page.generated) {
        lines.push(`_Generated reference page, not inlined. Fetch it from ${SITE}${page.url}._`);
      } else {
        lines.push(cleanBody(page.body));
      }
    }
  }

  return `${lines
    .join("\n")
    .replace(/\n{4,}/g, "\n\n\n")
    .trimEnd()}\n`;
}

// --------------------------------------------------------------------------

function main() {
  const sections = buildSections();

  const index = renderIndex(sections);
  const small = renderSmall(sections);
  const full = renderFull(sections);

  writeFileSync(join(publicDir, "llms.txt"), index);
  writeFileSync(join(publicDir, "llms-small.txt"), small);
  writeFileSync(join(publicDir, "llms-full.txt"), full);

  const pages = sections.flatMap((s) => s.pages).filter((p) => !p.external);
  const inlined = pages.filter((p) => !p.generated).length;
  console.log(
    `Wrote public/llms.txt (${pages.length} pages, ${Math.round(index.length / 1024)} KB), ` +
      `public/llms-small.txt (${Math.round(small.length / 1024)} KB) and ` +
      `public/llms-full.txt (${inlined} bodies inlined, ${pages.length - inlined} generated pages linked, ` +
      `${Math.round(full.length / 1024)} KB).`,
  );
}

export { SITE, buildSections, renderIndex, renderSmall, renderFull, cleanBody, abridgeBody };

// Only generate when run directly; the marketing generator imports the
// builders above without wanting the docs' own public/ files rewritten.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
