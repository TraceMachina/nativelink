#!/usr/bin/env node
// Anchor lint: every heading and every FAQ entry carries an explicit anchor.
//
// Fumadocs derives a heading's id from its text when no id is given. That is
// convenient and it is exactly the problem: the id is a function of the prose,
// so rewording a heading silently repoints every link that cited it. Humans
// notice a dead in-page link and scroll; agents cache the URL, follow it, land
// at the top of the page, and quote whatever is there.
//
// `/agents` promises machine readers that "a citation to a specific claim keeps
// resolving". This lint is what makes that promise structural rather than
// aspirational: an explicit `[#slug]` on every heading and an `id=` on every
// `<Accordion>` pins the anchor to the author's intent instead of to the
// current wording, so a heading can be rewritten without breaking a citation.
//
// Usage, from web/:
//   bun --filter @nativelink/docs lint:anchors
//   bun --filter @nativelink/docs lint:anchors --fix
// or directly:
//   node scripts/lint-anchors.mjs [--fix]
//
// `--fix` appends the anchor Fumadocs would have generated anyway, so running
// it never changes where an existing link lands; it only freezes it.
//
// Generated pages are skipped: their anchors are the generator's business, and
// hand-editing them would be overwritten on the next regeneration.
//
// Exit code is 1 if any heading or accordion is missing an explicit anchor.
//
// The markdown-parsing imports below (`github-slugger`, `remark-parse`,
// `remark-mdx`, `unified`, `unist-util-visit`) are not listed in this package's
// dependencies. They arrive hoisted into `web/node_modules` as transitive
// dependencies of Fumadocs, which owns the versions this script has to agree
// with anyway; it reuses `remarkHeading` from `fumadocs-core`, so parsing the
// tree with a different remark than Fumadocs uses would be the actual bug.
// Declaring them here would pin a second copy free to drift from that. If a
// Fumadocs upgrade ever drops one, this script fails loudly at import rather
// than silently mis-slugging, which is the failure mode worth having.

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { remarkHeading } from "fumadocs-core/mdx-plugins";
import Slugger from "github-slugger";
import remarkMdx from "remark-mdx";
import remarkParse from "remark-parse";
import { unified } from "unified";
import { visit } from "unist-util-visit";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = join(here, "..");
const contentDir = join(docsRoot, "content/docs");

// The provenance comment generated pages open with. Matching the comment form
// rather than the bare word keeps a page that merely mentions the marker in
// prose from being treated as generated.
const GENERATED_MARKER = "{/* AUTOGENERATED";
const FIX = process.argv.includes("--fix");

// --------------------------------------------------------------------------

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith(".mdx")) out.push(full);
  }
  return out;
}

/**
 * Blank out the frontmatter without changing the line count, so every node
 * position still points at the right line of the original file.
 */
function blankFrontmatter(source) {
  if (!source.startsWith("---")) return source;
  const end = source.indexOf("\n---", 3);
  if (end === -1) return source;
  const close = source.indexOf("\n", end + 1);
  const head = source.slice(0, close);
  return head.replace(/[^\n]/g, " ") + source.slice(close);
}

const processor = unified()
  .use(remarkParse)
  .use(remarkMdx)
  .use(remarkHeading, { generateToc: false });

/**
 * Parse a page and return what carries an anchor and what does not.
 *
 * Heading ids come from Fumadocs' own `remarkHeading`, so the id this lint
 * writes is byte-for-byte the id the site serves today.
 */
function inspect(source) {
  const tree = processor.parse(blankFrontmatter(source));
  processor.runSync(tree);

  const headings = [];
  const accordions = [];
  const taken = new Set();
  const totals = { headings: 0, accordions: 0 };

  visit(tree, "heading", (node) => {
    totals.headings += 1;
    const id = node.data?.hProperties?.id;
    if (id) taken.add(id);
    // `remarkHeading` strips `[#id]` off the trailing text node when it finds
    // one, so an explicit anchor is exactly the case where the raw line ends
    // in `[#…]`, so read the source line rather than the mutated node.
    headings.push({ line: node.position.start.line, endLine: node.position.end.line, id });
  });

  visit(tree, "mdxJsxFlowElement", (node) => {
    if (node.name !== "Accordion") return;
    totals.accordions += 1;
    const attrs = new Map();
    for (const attr of node.attributes ?? []) {
      if (attr.type !== "mdxJsxAttribute") continue;
      attrs.set(attr.name, typeof attr.value === "string" ? attr.value : null);
    }
    if (attrs.has("id")) {
      if (attrs.get("id")) taken.add(attrs.get("id"));
      return;
    }
    accordions.push({
      line: node.position.start.line,
      endLine: node.position.end.line,
      title: attrs.get("title") ?? "",
    });
  });

  return { headings, accordions, taken, totals };
}

/** A slug that does not collide with anything already claimed on the page. */
function uniqueSlug(text, taken) {
  const slugger = new Slugger();
  let slug = slugger.slug(text) || "section";
  let n = 2;
  while (taken.has(slug)) slug = `${slugger.slug(text) || "section"}-${n++}`;
  taken.add(slug);
  return slug;
}

// --------------------------------------------------------------------------

function main() {
  const files = walk(contentDir).sort();
  const problems = [];
  let fixedFiles = 0;
  let fixedAnchors = 0;
  let checkedHeadings = 0;
  let checkedAccordions = 0;
  let skipped = 0;

  for (const file of files) {
    const rel = relative(docsRoot, file);
    const source = readFileSync(file, "utf8");
    if (source.includes(GENERATED_MARKER)) {
      skipped += 1;
      continue;
    }

    let report;
    try {
      report = inspect(source);
    } catch (error) {
      problems.push({ file: rel, line: 1, message: `could not parse: ${error.message}` });
      continue;
    }

    checkedHeadings += report.totals.headings;
    checkedAccordions += report.totals.accordions;

    const lines = source.split("\n");
    const edits = [];

    for (const heading of report.headings) {
      const raw = lines[heading.line - 1];
      if (/\[#[^\]]+\]\s*$/.test(raw)) continue;
      if (heading.endLine !== heading.line) {
        problems.push({
          file: rel,
          line: heading.line,
          message: "heading spans multiple lines; add the anchor by hand",
        });
        continue;
      }
      if (!heading.id) {
        problems.push({ file: rel, line: heading.line, message: "heading has no derivable id" });
        continue;
      }
      edits.push({ index: heading.line - 1, next: `${raw.replace(/\s+$/, "")} [#${heading.id}]` });
      problems.push({
        file: rel,
        line: heading.line,
        message: `heading has no explicit anchor (would be \`[#${heading.id}]\`)`,
      });
    }

    for (const accordion of report.accordions) {
      const raw = lines[accordion.line - 1];
      const id = uniqueSlug(accordion.title, report.taken);
      if (!/\stitle=("[^"]*"|\{[^}]*\})/.test(raw)) {
        problems.push({
          file: rel,
          line: accordion.line,
          message: "accordion has no id and no single-line title to derive one from",
        });
        continue;
      }
      edits.push({
        index: accordion.line - 1,
        next: raw.replace(/(\stitle=(?:"[^"]*"|\{[^}]*\}))/, `$1 id="${id}"`),
      });
      problems.push({
        file: rel,
        line: accordion.line,
        message: `accordion has no explicit id (would be \`id="${id}"\`)`,
      });
    }

    if (FIX && edits.length > 0) {
      for (const edit of edits) lines[edit.index] = edit.next;
      writeFileSync(file, lines.join("\n"));
      fixedFiles += 1;
      fixedAnchors += edits.length;
    }
  }

  console.log(
    `Checked ${checkedHeadings} heading(s) and ${checkedAccordions} accordion(s) across ` +
      `${files.length - skipped} page(s); skipped ${skipped} generated page(s).`,
  );

  if (FIX) {
    console.log(`Pinned ${fixedAnchors} anchor(s) across ${fixedFiles} page(s).`);
    return;
  }

  if (problems.length === 0) {
    console.log("Every heading and accordion carries an explicit anchor.");
    return;
  }

  console.error(`\n${problems.length} missing anchor(s):`);
  for (const p of problems) console.error(`  ${p.file}:${p.line}  ${p.message}`);
  console.error("\nRun `bun --filter @nativelink/docs lint:anchors --fix` to pin them.");
  process.exitCode = 1;
}

main();
